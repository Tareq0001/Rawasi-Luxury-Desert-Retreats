export class I18nManager {
  private currentLang: Language = 'ar';
  private listeners: ((lang: Language) => void)[] = [];

  constructor() {
    const saved = localStorage.getItem('rawasi_lang') as Language;
    if (saved && (saved === 'ar' || saved === 'en')) {
      this.currentLang = saved;
    }
    this.applyToDOM();
  }

  public getLang(): Language {
    return this.currentLang;
  }

  public isAr(): boolean {
    return this.currentLang === 'ar';
  }

  public setLang(lang: Language) {
    if (this.currentLang === lang) return;
    this.currentLang = lang;
    localStorage.setItem('rawasi_lang', lang);
    this.applyToDOM();
    this.notify();
  }

  public toggleLang(): Language {
    const next = this.currentLang === 'ar' ? 'en' : 'ar';
    this.setLang(next);
    return next;
  }

  public t(key: keyof typeof TRANSLATIONS['ar']): string {
    return TRANSLATIONS[this.currentLang][key] || TRANSLATIONS['ar'][key] || key;
  }

  public onLanguageChange(cb: (lang: Language) => void) {
    this.listeners.push(cb);
  }

  private notify() {
    for (const cb of this.listeners) {
      cb(this.currentLang);
    }
  }

  private applyToDOM() {
    const isArabic = this.currentLang === 'ar';
    document.documentElement.lang = this.currentLang;
    document.documentElement.dir = isArabic ? 'rtl' : 'ltr';
    document.body.classList.toggle('lang-ar', isArabic);
    document.body.classList.toggle('lang-en', !isArabic);
  }
}

export const i18n = new I18nManager();
